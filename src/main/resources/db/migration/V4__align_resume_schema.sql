ALTER TABLE `resumes`
    CHANGE COLUMN `uploader_id` `user_id` BIGINT NOT NULL COMMENT 'User ID',
    MODIFY COLUMN `file_type` VARCHAR(100) NOT NULL COMMENT 'Uploaded media type',
    MODIFY COLUMN `status` VARCHAR(32) NOT NULL DEFAULT 'PARSING' COMMENT 'Parsing status',
    ADD COLUMN `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP COMMENT 'Update time';

UPDATE `resumes`
SET `status` = CASE `status`
    WHEN 'PENDING' THEN 'PARSING'
    WHEN 'QUEUED' THEN 'PARSING'
    WHEN 'PROCESSING' THEN 'PARSING'
    WHEN 'SUCCESS' THEN 'COMPLETED'
    ELSE `status`
END;
